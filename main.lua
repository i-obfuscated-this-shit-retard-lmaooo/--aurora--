local function fetch(retries)
    retries = retries or 3
    for i = 1, retries do
        local ok, res = pcall(game.HttpGet, game, url)
        if ok then return res end
        w(0.5 * i)
    end
    error(h2s('4661696c656420746f206665746368'), 0)
end

